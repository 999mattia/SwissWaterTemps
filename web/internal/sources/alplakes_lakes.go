type alplakesLake struct {
	name string
	// waterBody holds another common name, so searching for it finds the lake.
	waterBody string
	lat, lon  float64
	// rmse is the model's typical surface error in °C, from Eawag's validation
	// against measurements.
	rmse float64
	// basin: the lake shares its BAFU level gauge with other basins, or has no
	// gauge, so measured stations name the basin (station.Basin) to hide it.
	basin bool
}

